#-------------- PATCH EMBED -----------------#

class PatchEmbed(nn.Module):
    '''
    Image to Patch Embedding by convolution.
    '''
    def __init__(
        self, 
        patch_size: Tuple = (16, 16), 
        in_chans: int = 3, 
        embed_dim: int = 768,
    ):
        super().__init__()
        self.proj = nn.Conv2d(in_chans, embed_dim, kernel_size=patch_size, stride=patch_size)
        # NOTE:
        # If we apply depthwise convolutions, we need to pass the new T as well, as the embedding 
        # mechnics effectively changes this. We currently do not - so it is fine. But it is a design flaw.

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor,int,int]:
        '''
        Args:
            x: assumes shape-order: b c t h w = batch_size, channels, temporal, height, width.
        
        Returns
            Tuple: patchified data per frame. x.shape = (B x T, x_patches_h x x_patches_w, embed_dim), 
            where x_patches_h (number of patches fitted on the height), x_patches_w (number of patches fitted on the width)
        '''
        x = einops.rearrange(x, 'b c t h w -> (b t) c h w')
        x = self.proj(x)
        x_patches_h = x.size(-2)
        x_patches_w = x.size(-1)
        x = x.flatten(2).transpose(1, 2)
        return x, x_patches_h, x_patches_w
    
